// glyphs[c] row r bit (GlyphW-1-x) = ink at (x, r). Characters with no
// glyph draw as a box.
var glyphs [128][GlyphH]uint8

var boxGlyph = [GlyphH]uint8{0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F, 0}

func init() {
	for c := range glyphs {
		glyphs[c] = boxGlyph
	}
	for c, src := range glyphSource {
		for r, row := range strings.Fields(src) {
			var bits uint8
			for x := 0; x < GlyphW; x++ {
				if row[x] == '#' {
					bits |= 1 << (GlyphW - 1 - x)
				}
			}
			glyphs[c][r] = bits
		}
	}
}

// glyph returns the bitmap for c.
func glyph(c byte) *[GlyphH]uint8 {
	if c >= 128 {
		return &boxGlyph
	}
	return &glyphs[c]
}
